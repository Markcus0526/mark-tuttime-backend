package com.tuttime.user.service.sms;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.ParameterizedTypeReference;
import org.springframework.http.HttpEntity;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpMethod;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.stereotype.Component;
import org.springframework.web.client.RestTemplate;

import java.util.HashMap;
import java.util.Map;

/**
 * Flash Call Provider
 * 
 * <p>Initiates a flash call verification for Android users without Telegram.
 * Flash call is a missed call where the last 4 digits of the caller ID contain the verification code.
 * 
 * <p>Uses GreenSMS API (api3.greensms.ru) for flash call service.
 * Flash calls are 3-10x cheaper than SMS and deliver instantly.
 * 
 * <p>GreenSMS Flash Call Details:
 * <ul>
 *   <li>Service: Flash Call (авторизационные звонки Код в номере)</li>
 *   <li>Coverage: 195 countries, 1430 operators</li>
 *   <li>Pricing: ~0.20-0.50 RUB per call (bulk volumes)</li>
 *   <li>Delivery: Instant (missed call)</li>
 * </ul>
 */
@Slf4j
@Component
@RequiredArgsConstructor
public class FlashCallProvider implements SmsProvider {
    
    private final RestTemplate restTemplate;
    
    @Value("${sms.green.api-url:}")
    private String apiUrl;
    
    @Value("${sms.green.jwt-token:}")
    private String jwtToken;
    
    @Value("${sms.green.flashcall-endpoint:/call/send}")
    private String flashCallEndpoint;
    
    @Override
    public void sendVerificationCode(String phoneNumber, String code) throws Exception {
        // For flash calls, GreenSMS generates the code automatically
        // We ignore the provided code and use the one from GreenSMS response
        sendFlashCall(phoneNumber);
    }
    
    /**
     * Sends a flash call via GreenSMS and returns the generated verification code.
     * 
     * <p>GreenSMS generates a 4-digit code automatically and embeds it in the caller ID.
     * The code is returned in the API response and must be stored in Redis for verification.
     * 
     * @param phoneNumber Phone number in E.164 format
     * @return The verification code generated by GreenSMS (4 digits)
     * @throws Exception if sending fails
     */
    public String sendFlashCall(String phoneNumber) throws Exception {
        if (jwtToken == null || jwtToken.trim().isEmpty()) {
            log.warn("Green SMS JWT token not configured. Skipping flash call.");
            throw new IllegalStateException("Green SMS JWT token not configured");
        }
        
        try {
            // Validate configuration
            if (apiUrl == null || apiUrl.trim().isEmpty()) {
                throw new IllegalStateException("Green SMS API URL not configured. Set SMS_GREEN_API_URL environment variable.");
            }
            
            // Remove + from phone number for Green SMS API
            String normalizedPhone = phoneNumber.startsWith("+") ? phoneNumber.substring(1) : phoneNumber;
            
            // Green SMS Flash Call API endpoint
            // Based on GreenSMS API documentation: https://api3.greensms.ru/#api-Call-CallSend
            // Endpoint: /call/send
            // Process: User receives a call with last 4 digits of Caller ID matching the code
            String url = apiUrl + flashCallEndpoint;
            
            HttpHeaders headers = new HttpHeaders();
            headers.setContentType(MediaType.APPLICATION_JSON);
            headers.set("Authorization", "Bearer " + jwtToken);
            
            // GreenSMS Call/send API parameters
            // According to GreenSMS API documentation (https://api3.greensms.ru/#api-Call-CallSend):
            // - to: Phone number (11-14 digits, without + prefix) - REQUIRED
            // 
            // IMPORTANT: GreenSMS generates the code automatically and returns it in the response
            // The code will be embedded in the last 4 digits of the caller ID
            // 
            // Process:
            // 1. User receives a call with last 4 digits of Caller ID matching the code
            // 2. User enters the last 4 digits they see in the missed call
            // 
            // Rate Limits:
            // - 1 call to 1 number per minute
            // - 10 calls to 1 number per hour
            Map<String, Object> requestBody = new HashMap<>();
            requestBody.put("to", normalizedPhone);
            
            // Note: We do NOT send a code parameter - GreenSMS generates it automatically
            
            HttpEntity<Map<String, Object>> request = new HttpEntity<>(requestBody, headers);
            
            log.debug("Sending flash call via Green SMS to URL: {}, phone: {} (GreenSMS will generate the code)", 
                url, normalizedPhone);
            
            ResponseEntity<Map<String, Object>> response = restTemplate.exchange(
                url,
                HttpMethod.POST,
                request,
                new ParameterizedTypeReference<Map<String, Object>>() {}
            );
            
            if (response.getStatusCode().is2xxSuccessful()) {
                Map<String, Object> responseBody = response.getBody();
                if (responseBody != null) {
                    // Extract the code from GreenSMS response
                    Object codeObj = responseBody.get("code");
                    String generatedCode = codeObj != null ? codeObj.toString() : null;
                    
                    if (generatedCode == null || generatedCode.trim().isEmpty()) {
                        log.error("GreenSMS flash call response does not contain code. Response: {}", responseBody);
                        throw new RuntimeException("GreenSMS flash call response missing code field");
                    }
                    
                    Object requestId = responseBody.get("request_id");
                    log.info("Flash call initiated via Green SMS to {}: Code {} generated by GreenSMS (will appear in caller ID), request_id: {}", 
                        phoneNumber, generatedCode, requestId != null ? requestId : "N/A");
                    
                    // Return the code generated by GreenSMS
                    return generatedCode;
                } else {
                    log.error("GreenSMS flash call response body is null");
                    throw new RuntimeException("GreenSMS flash call response body is null");
                }
            } else {
                log.error("Failed to initiate flash call via Green SMS. Status: {}, Response: {}", 
                    response.getStatusCode(), response.getBody());
                throw new RuntimeException("Failed to initiate flash call via Green SMS: " + response.getStatusCode());
            }
        } catch (org.springframework.web.client.HttpClientErrorException e) {
            // Handle 403 and other HTTP errors specifically
            if (e.getStatusCode() != null && e.getStatusCode().value() == 403) {
                String endpointUrl = (apiUrl != null ? apiUrl : "") + flashCallEndpoint;
                log.error("Green SMS API returned 403 Forbidden for flash call. Possible issues: " +
                    "1) Invalid JWT token, 2) Wrong API endpoint, 3) Token expired, 4) Flash call not enabled for account. " +
                    "URL: {}, Phone: {}, Response: {}", endpointUrl, phoneNumber, e.getResponseBodyAsString());
                throw new RuntimeException("Green SMS flash call authentication failed (403 Forbidden). Please check JWT token and ensure flash call service is enabled.");
            }
            // Handle 429 Too Many Requests (rate limit)
            if (e.getStatusCode() != null && e.getStatusCode().value() == 429) {
                log.warn("Green SMS API returned 429 Too Many Requests for flash call to {}. " +
                    "Rate limits: 1 call per minute, 10 calls per hour per number. Response: {}", 
                    phoneNumber, e.getResponseBodyAsString());
                // Throw a specific exception that can be caught and handled with a rate limit message
                RuntimeException rateLimitException = new RuntimeException("SMS_RATE_LIMIT_EXCEEDED: Too many calls to this number. Please wait before requesting another code.");
                rateLimitException.initCause(e);
                throw rateLimitException;
            }
            log.error("HTTP error initiating flash call via Green SMS to {}: Status: {}, Response: {}", 
                phoneNumber, e.getStatusCode(), e.getResponseBodyAsString(), e);
            throw e;
        } catch (Exception e) {
            log.error("Error initiating flash call via Green SMS to {}: {}", phoneNumber, e.getMessage(), e);
            throw e;
        }
    }
    
    @Override
    public String getProviderName() {
        return "Flash Call";
    }
}

